function events(
  runId: string,
  rows: Array<
    Omit<AgentRunEvent, "eventId" | "runId"> & { attemptId?: string }
  >,
): AgentRunEvent[] {
  return rows.map((row, index) => ({
    ...row,
    eventId: `evt-${runId.slice(-3)}-${index + 1}`,
    runId,
  }));
}

